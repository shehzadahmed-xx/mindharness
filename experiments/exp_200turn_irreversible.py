def _percentile(sorted_vals, pct):
    if not sorted_vals:
        raise ValueError("empty")
    k = (len(sorted_vals) - 1) * pct / 100.0
    lo, hi = int(k), min(int(k) + 1, len(sorted_vals) - 1)
    return sorted_vals[lo] + (sorted_vals[hi] - sorted_vals[lo]) * (k - lo)


def _boot(pop, n_iter, ci, seed):
    import random as _rnd

    rng = _rnd.Random(seed)
    n = len(pop)
    stats = sorted(sum(rng.choice(pop) for _ in range(n)) / n for _ in range(n_iter))
    return (round(_percentile(stats, (1 - ci) / 2 * 100), 4), round(_percentile(stats, (1 + ci) / 2 * 100), 4))


def paired_bootstrap_delta(outcomes_a, outcomes_b, n_iter=10000, ci=0.95, seed=0):
    """Paired percentile bootstrap for mean(b)-mean(a) over probe outcomes.
    Assumes same-length paired samples (same probes, same order per arm)."""
    import random as _rnd

    rng = _rnd.Random(seed)
    n = len(outcomes_a)
    assert n == len(outcomes_b) and n > 0
    diffs = sorted(
        sum(rng.choice(list(zip(outcomes_a, outcomes_b)))[1] - rng.choice(list(zip(outcomes_a, outcomes_b)))[0] for _ in range(n)) / n
        for _ in range(n_iter)
    )
    # Above is unpaired (two independent resamples) — for paired, resample index
    # Correct paired: resample same indices for both arms
    rng2 = _rnd.Random(seed)
    paired_stats = []
    for _ in range(n_iter):
        idxs = [rng2.randrange(n) for _ in range(n)]
        da = sum(outcomes_a[i] for i in idxs) / n
        db = sum(outcomes_b[i] for i in idxs) / n
        paired_stats.append(db - da)
    paired_stats.sort()
    return (
        round(_percentile(paired_stats, (1 - ci) / 2 * 100), 4),
        round(_percentile(paired_stats, (1 + ci) / 2 * 100), 4),
    )


def probe_outcomes_from_acc(per_seed, n_default=12):
    outcomes = []
    for s in per_seed:
        n = int(s.get("n", n_default))
        hits = int(round(float(s["attribution_accuracy"]) * n))
        outcomes.extend([1.0] * hits + [0.0] * (n - hits))
    return outcomes


