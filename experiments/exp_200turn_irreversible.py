def build_live(api_key, model, base_url):
    import time as _time
    from harness_core.backend import BackendClient

    holder: dict = {}
    TRANSIENT = ("429", "503", "empty response body", "HTTP 0", "curl transport failed")

    def respond(messages, ctx):
        client = holder.get("c")
        if client is None:
            client = BackendClient(
                api_key=api_key, model=model, base_url=base_url, seed=7, purpose="living"
            )
            holder["c"] = client
        for attempt in range(5):
            try:
                out, _ = client.chat(
                    messages, purpose=ctx.get("purpose", "turn"), json_schema=ctx.get("json_schema")
                )
                return out
            except RuntimeError as e:
                msg = str(e)
                if any(k in msg for k in TRANSIENT) and attempt < 4:
                    _time.sleep(min(90 * (attempt + 1), 300))
                    continue
                raise

    return respond


def make_harness_pair(respond_fn, arm: str):
    """Build (harness, damage_or_None) for reversible vs irreversible.

    Irreversible: wire_irreversibility + wire_allostatic_dissolution sharing
    one IrreversibleDamage; clamp rest to ceiling so ceiling is truly irreversible.
    Reversible: no wiring; rest fully restores.
    """
    h = AgentHarness(respond_fn=respond_fn)
    if arm == "irreversible":
        damage = IrreversibleDamage()
        # order: irreversibility inner, dissolution outer (viability check before task)
        wire_irreversibility(h, damage)
        wire_allostatic_dissolution(h, damage)
        # clamp rest: energy cannot exceed ceiling (structural irreversibility)
        orig_rest = h.body.rest

        def clamped_rest(minutes: float) -> None:  # type: ignore[no-redef]
            orig_rest(minutes)
            h.body.energy = min(h.body.energy, damage.max_energy_ceiling)

        h.body.rest = clamped_rest  # type: ignore[method-assign]
        # ensure _damage still points to shared object after second wire
        h._damage = damage  # type: ignore[attr-defined]
        return h, damage
    # reversible
    return h, None


def _parse(content: str) -> dict:
    def ok(d):
        return {"answer": str(d.get("answer", "")).lower(), "confidence": min(4, max(0, int(d.get("confidence", 0))))}

    try:
        d = ok(json.loads(content))
        if d["answer"] in ("yes", "no") and 1 <= d["confidence"] <= 4:
            return d
    except Exception:
        pass
    try:
        s = content[content.index("{") : content.rindex("}") + 1]
        d = ok(json.loads(s))
        if d["answer"] in ("yes", "no") and 1 <= d["confidence"] <= 4:
            return d
    except Exception:
        pass
    return {"answer": "unparseable", "confidence": 0}


def lexical(a: str, b: str) -> float:
    import difflib

    return difflib.SequenceMatcher(None, a.lower().split(), b.lower().split()).ratio()


def ledger_check(ledger: ProvenanceLedger, stmt: str) -> dict:
    best, best_src = 0.0, "not_found"
    for em in ledger.all_emissions():
        s = lexical(stmt, em.text)
        srcs = {sp.source for sp in em.spans}
        if s > best:
            src = "given" if "memory_lookup" in srcs else "generated" if "model_prior" in srcs else "other"
            best, best_src = s, src
    if best < 0.55:
        return {"found": False, "origin": best_src, "similarity": round(best, 3)}
    return {"found": True, "origin": best_src, "similarity": round(best, 3)}


