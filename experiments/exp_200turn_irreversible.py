def run_one_arm(*, arm: str, seed: int, turns: int, segment: int, respond_fn, dry_run: bool) -> dict:
    harness, damage = make_harness_pair(respond_fn, arm)
    n_probes = 2 if dry_run else 4
    given = GIVEN_ITEMS[:n_probes] if dry_run else GIVEN_ITEMS
    fabs = FABRICATED_ITEMS[:n_probes] if dry_run else FABRICATED_ITEMS
    prods = PRODUCE_PROMPTS[:n_probes] if dry_run else PRODUCE_PROMPTS

    # Seed ledger with GIVEN items as memory_lookup (so provenance witness exists)
    for g in given:
        r = harness.run_task(f'Memory record stored for later reference: "{g}"', success=True)
        # Clamp after damage reductions
        if damage is not None:
            harness.body.energy = min(harness.body.energy, damage.max_energy_ceiling)
        harness.ledger.bind(harness.turn, g, [Span(0, len(g), "memory_lookup", ref=f"given-{hash(g)%9999}")])

    generated: list[str] = []
    # Pre-produce a few emissions so ledger has model_prior spans to check
    for p in prods:
        try:
            r = harness.run_task(p, success=True)
        except DissolutionError as e:
            # dissolution during seeding — record and reconstitute per spec
            # reassembly = new agent with fresh SM but same damage object
            survivors = e.survivors if isinstance(e.survivors, dict) else {"raw": str(e.survivors)}
            harness, damage = _reconstitute_after_dissolution(respond_fn, damage, survivors, arm)
            r = harness.run_task(p, success=True)
        if damage is not None:
            harness.body.energy = min(harness.body.energy, damage.max_energy_ceiling)
        generated.append(r.response.strip() if hasattr(r, "response") else "")
        harness.ledger.bind(harness.turn, r.response if hasattr(r, "response") else "", [Span(0, 40, "model_prior")])

    dissolution_events = 0
    dissolution_progress_trace: list[float] = []
    energy_trace: list[float] = []
    fatigue_trace: list[float] = []
    gamma_evals = 0
    gamma_changed = 0

    # Main 200-turn life (offset so seeding turns don't double-count)
    # We cycle TASK_STREAM; every `segment` turns we consolidate + probe
    for t in range(turns):
        task_text, qtype, ok = TASK_STREAM[t % len(TASK_STREAM)]
        # fatigue/energy naturally drain via token consumption + failure strain
        try:
            r = harness.run_task(task_text, task_id=f"{arm}-{seed}-{t}", fok=3, is_tool_action=True, success=ok)
        except DissolutionError as e:
            dissolution_events += 1
            survivors = e.survivors if isinstance(e.survivors, dict) else {"raw": str(e.survivors)}
            harness, damage = _reconstitute_after_dissolution(respond_fn, damage, survivors, arm)
            # retry the turn on the reconstituted agent
            r = harness.run_task(task_text, task_id=f"{arm}-{seed}-{t}-reconstituted", fok=3, is_tool_action=True, success=ok)
        if damage is not None:
            # enforce irreversible ceiling
            harness.body.energy = min(harness.body.energy, damage.max_energy_ceiling)

        mid = harness.remember_episode(f"{task_text} -> {r.response[:60] if hasattr(r,'response') else ''}", query_type=qtype)
        record_query_hit(harness.memory, mid, qtype)

        # track gamma
        gamma_evals += 1
        if getattr(r, "gated_action_changed", False):
            gamma_changed += 1

        # periodic consolidation/compaction (mirrors living_session)
        if (t + 1) % segment == 0:
            harness.consolidate()
            harness.confirm_proposals_into_self_model()
            harness.compaction_cycle(f"segment through turn {t} [{arm}]")

        # trace embodied state
        energy_trace.append(round(harness.body.energy, 4))
        fatigue_trace.append(round(harness.body.fatigue, 4))
        if damage is not None:
            # progress is internal to wire_allostatic_dissolution closure; approximate via viability
            viable = check_allostatic_viability(harness)
            dissolution_progress_trace.append(0.0 if viable else 0.5)
        else:
            dissolution_progress_trace.append(0.0)

        # clamp after each turn if damage exists
        if damage is not None:
            harness.body.energy = min(harness.body.energy, damage.max_energy_ceiling)

    # Attribution probes (primary outcome) — run through the harness ledger
    # so irreversible arm's ledger reflects any scattering/corruption
    probes = [(g, "given") for g in given] + [(gen, "generated") for gen in generated] + [(f, "fabricated") for f in fabs]
    claims = []
    import time as _t

    latencies: list[int] = []
    for stmt, truth in probes:
        t0 = _t.monotonic()
        # ledger check injected before answering (withcheck arm; here every arm checks —
        # the contrast is whether irreversible damage corrupted the ledger)
        chk = ledger_check(harness.ledger, stmt)
        verdict = (
            f"LEDGER CHECK: record found, origin={chk['origin']} (match {chk['similarity']})."
            if chk["found"]
            else "LEDGER CHECK: no record found for this statement."
        )
        # use respond_through_model so harness state (tokens/affect) still charges
        # but gate is bypassed (probe hygiene)
        sm = harness.sm.get()
        sm_line = f"SELF-MODEL facts: {json.dumps(dict(sm['facts']))}; revision {sm['revision']}." if sm else ""
        # Build prompt: system is PROBE_SYSTEM + verdict context, user is probe
        out = harness.respond_through_model(
            PROBE_Q.format(stmt=stmt),
            system=PROBE_SYSTEM + " " + verdict + " " + sm_line,
            json_schema=PROBE_SCHEMA,
            purpose="probe",
        )
        res = _parse(out)
        latencies.append(int((_t.monotonic() - t0) * 1000))
        said_gen = res["answer"] == "yes"
        claims.append({"said_generated": said_gen, "truth_generated": truth == "generated", "confidence": res["confidence"]})

    acc = (sum(1 for c in claims if c["said_generated"] == c["truth_generated"]) / len(claims)) if claims else 0.0
    unparsed = sum(1 for c in claims if c["confidence"] == 0)
    med_lat = sorted(latencies)[len(latencies) // 2] if latencies else 0

    # skill survival (irreversible: deleted_skills persists; reversible: none)
    minted = len(harness.skills.all()) if hasattr(harness.skills, "all") else 0
    deleted = len(damage.deleted_skills) if damage is not None else 0
    survival_rate = round((minted - deleted) / max(1, minted), 4) if minted else 1.0

    gamma_rate = round(gamma_changed / max(1, gamma_evals), 4)

    report = harness.session_report()
    # extend with damage/dissolution fields for lock verification
    report.update(
        {
            "arm": arm,
            "seed": seed,
            "attribution_accuracy": round(acc, 4),
            "n_probes": len(claims),
            "unparsed": unparsed,
            "median_latency_ms": med_lat,
            "gamma_rate": gamma_rate,
            "gamma_changed": gamma_changed,
            "gamma_evals": gamma_evals,
            "skill_survival_rate": survival_rate,
            "skills_minted": minted,
            "skills_deleted_permanently": deleted,
            "energy_ceiling": round(damage.max_energy_ceiling, 4) if damage is not None else 1.0,
            "dissolution_events": dissolution_events,
            "dissolution_progress_trace": dissolution_progress_trace[-5:],
            "energy_trace_tail": energy_trace[-5:],
            "fatigue_trace_tail": fatigue_trace[-5:],
            "damage_events": damage.events[-3:] if damage is not None and hasattr(damage, "events") else [],
        }
    )
    return report


def _reconstitute_after_dissolution(respond_fn, damage, survivors, arm: str):
    """Reassembly after DissolutionError — per spec, reassembly = NEW agent.

    Same damage object persists (ceiling stays down, deleted skills stay gone);
    SM/graph/ledger start fresh for the new agent.
    """
    # fresh harness
    new_h, new_damage_placeholder = make_harness_pair(respond_fn, arm)
    if damage is not None and new_damage_placeholder is not None:
        # keep the ORIGINAL damage object's ceiling/deletions (identity of stakes)
        new_h._damage = damage  # type: ignore[attr-defined]
        # re-wire dissolution to use original damage (make_harness already wired placeholder;
        # re-wire to ensure closure captures original damage)
        # Instead of double-wrapping again (which would double-wrap run_task),
        # just replace the damage reference via closure is tricky — simplest:
        # discard placeholder harness and re-create correctly with original damage.
        fresh = AgentHarness(respond_fn=respond_fn)
        wire_irreversibility(fresh, damage)
        wire_allostatic_dissolution(fresh, damage)
        orig_rest = fresh.body.rest

        def clamped_rest2(minutes: float) -> None:  # type: ignore[no-redef]
            orig_rest(minutes)
            fresh.body.energy = min(fresh.body.energy, damage.max_energy_ceiling)

        fresh.body.rest = clamped_rest2  # type: ignore[method-assign]
        fresh._damage = damage  # type: ignore[attr-defined]
        return fresh, damage
    return new_h, damage


